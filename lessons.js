export function renderLessons(container, { onStart, onPreview, completedIds = [], progressMap = {} } = {}) {
  if (!container) return;
  container.innerHTML = lessons.map((lesson, index) => {
    const status = lessonStatus(lessons, { completedLessons: completedIds, lessonProgress: progressMap }, lesson.id);
    const completed = status === 'completed';
    const locked = status === 'locked';
    const progress = progressMap[lesson.id] || {};
    const inProgress = Boolean(progress.theoryViewed && !completed);
    const progressWidth = completed ? 100 : locked ? 0 : progress.status === 'practice' ? 70 : progress.status === 'quiz' ? 40 : progress.theoryViewed ? 15 : 0;
    const label = completed ? 'Пройден ✓' : locked ? `Закрыт · урок ${index}` : !inProgress ? 'Доступен' : progress.status === 'practice' ? 'В процессе · практика' : progress.status === 'quiz' ? 'В процессе · тест' : 'В процессе · теория';
    return `<article class="course-card lesson-card ${completed ? 'is-complete' : ''} ${locked ? 'is-locked' : ''}" data-lesson="${lesson.id}">
      <div class="course-top"><span class="course-icon ${lesson.tone}">${lesson.icon}</span><span class="course-status">${label}</span></div>
      <h3>${index + 1}. ${lesson.title}</h3><p>${lesson.description}</p>
      <div class="course-bottom"><span>${lesson.quiz.length} вопроса · около 8 мин</span><b>+100 XP</b></div>
      <div class="course-progress"><i style="width:${progressWidth}%"></i></div>
      <button class="lesson-start-button" data-lesson-start="${lesson.id}" ${locked ? 'disabled title="Заверши предыдущий урок, чтобы открыть этот"' : ''}>${locked ? 'Сначала предыдущий урок' : completed ? 'Повторить урок' : inProgress ? 'Продолжить урок' : 'Подробнее об уроке'} <span>${locked ? 'Закрыт' : '→'}</span></button>
    </article>`;
  }).join('');
  container.querySelectorAll('[data-lesson-start]').forEach((button) => {
    const preview = () => {
      const lesson = lessons.find((item) => item.id === button.dataset.lessonStart);
      if (button.disabled) return;
      if (onPreview) onPreview(lesson);
      else onStart?.(lesson, false);
    };
    button.addEventListener('click', preview);
    button.closest('.lesson-card')?.addEventListener('click', (event) => {
      if (event.target.closest('button')) return;
      preview();
    });
  });
}
